-- Alterna — app Soporte (soporte.html): tickets de Zoho Desk creados por el servidor.
-- El usuario solo inicia sesión en Alterna; la función "soporte" crea el ticket en Zoho Desk
-- a su nombre con una conexión de la empresa que un administrador configura una sola vez.

-- Conexión de la empresa con Zoho Desk (una sola fila). Solo la lee la función del servidor:
-- sin políticas ni permisos para anon/authenticated, nadie la ve desde el navegador.
create table if not exists public.zoho_desk_config (
  id              int primary key default 1 check (id = 1),
  client_id       text not null,
  client_secret   text not null,
  refresh_token   text not null,
  servidor        text not null default 'https://accounts.zoho.com',
  actualizado     timestamptz not null default now(),
  actualizado_por bigint references public.usuarios(id) on delete set null
);
alter table public.zoho_desk_config enable row level security;
revoke all on public.zoho_desk_config from public, anon, authenticated;

-- Registro de tickets enviados (historial y límite de envíos por usuario).
create table if not exists public.soporte_tickets (
  id          bigint generated by default as identity primary key,
  usuario_id  bigint not null references public.usuarios(id) on delete cascade,
  ticket_id   text,
  numero      text,
  asunto      text not null,
  created_at  timestamptz not null default now()
);
create index if not exists soporte_tickets_usuario_fecha on public.soporte_tickets (usuario_id, created_at desc);
alter table public.soporte_tickets enable row level security;
revoke all on public.soporte_tickets from public, anon, authenticated;

-- La app en el catálogo (si ya se creó desde el panel, no se toca)
insert into public.aplicaciones (clave, nombre, descripcion, url, color, orden)
