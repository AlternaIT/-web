-- Alterna — catálogo de aplicaciones y accesos por usuario.
-- Después del login, cada usuario elige entre las aplicaciones a las que tiene acceso.
-- Todo se configura aquí, sin tocar código:
--   · aplicaciones: nombre, descripción, logo, color, enlace, orden, activa.
--   · usuarios_aplicaciones: qué usuario entra a qué aplicación.
-- Los administradores (área de IT) entran a todas las aplicaciones activas.
-- "clave" es el identificador fijo que usan las páginas para validar el acceso
-- ('it' = dashboard.html, 'ia' = ia.html). Para una app nueva basta con insertar una fila.

create table if not exists public.aplicaciones (
  id          bigint generated by default as identity primary key,
  clave       text not null unique,
  nombre      text not null,
  descripcion text,
  url         text not null,          -- ruta dentro del sitio (ia.html) o dirección completa (https://…)
  logo_url    text,                   -- imagen del logo (ruta o https://…); si está vacío se muestran las iniciales
  color       text default '#3a3a3c', -- color de fondo del icono
  orden       int  not null default 0,
  activa      boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.usuarios_aplicaciones (
  usuario_id    bigint not null references public.usuarios(id) on delete cascade,
  aplicacion_id bigint not null references public.aplicaciones(id) on delete cascade,
  created_at    timestamptz not null default now(),
  primary key (usuario_id, aplicacion_id)
);

insert into public.aplicaciones (clave, nombre, descripcion, url, logo_url, color, orden) values
