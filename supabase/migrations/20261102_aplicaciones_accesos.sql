on conflict (clave) do nothing;

-- ¿El usuario tiene acceso a la aplicación? (admins: a todas las activas)
create or replace function public.usuario_tiene_acceso(p_usuario bigint, p_clave text) returns boolean
 language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.aplicaciones a
    where a.clave = p_clave and a.activa
      and (
        exists (select 1 from public.usuarios u where u.id = p_usuario and u.activo and u.rol = 'admin')
        or exists (select 1 from public.usuarios_aplicaciones ua
                   join public.usuarios u on u.id = ua.usuario_id and u.activo
                   where ua.usuario_id = p_usuario and ua.aplicacion_id = a.id)
      )
  )
$$;

-- Lo mismo para la sesión actual (header x-app-token).
create or replace function public.app_tiene_acceso(p_clave text) returns boolean
 language sql stable security definer set search_path = public as $$
  select public.usuario_tiene_acceso(public.app_usuario_id(), p_clave)
$$;

-- Aplicaciones de la sesión actual, para la página de selección.
create or replace function public.mis_aplicaciones()
 returns table(clave text, nombre text, descripcion text, url text, logo_url text, color text)
 language plpgsql stable security definer set search_path = public as $$
declare uid bigint := public.app_usuario_id();
begin
  if uid is null then raise exception 'sesion_invalida' using errcode = '28000'; end if;
  return query
    select a.clave, a.nombre, a.descripcion, a.url, a.logo_url, a.color
    from public.aplicaciones a
    where a.activa and public.usuario_tiene_acceso(uid, a.clave)
    order by a.orden, a.nombre;
end $$;

revoke all on function public.usuario_tiene_acceso(bigint, text) from public, anon, authenticated;
grant execute on function public.usuario_tiene_acceso(bigint, text) to service_role;
grant execute on function public.app_tiene_acceso(text), public.mis_aplicaciones() to anon, authenticated;

-- Catálogo y accesos: cualquier sesión lee; solo administradores modifican.
alter table public.aplicaciones enable row level security;
alter table public.usuarios_aplicaciones enable row level security;
drop policy if exists aplicaciones_select on public.aplicaciones;
drop policy if exists aplicaciones_admin on public.aplicaciones;
drop policy if exists accesos_select on public.usuarios_aplicaciones;
drop policy if exists accesos_admin on public.usuarios_aplicaciones;
create policy aplicaciones_select on public.aplicaciones for select to anon, authenticated
  using ((select public.app_usuario_id()) is not null);
create policy aplicaciones_admin on public.aplicaciones for all to anon, authenticated
  using ((select public.app_es_admin())) with check ((select public.app_es_admin()));
create policy accesos_select on public.usuarios_aplicaciones for select to anon, authenticated
  using (usuario_id = (select public.app_usuario_id()) or (select public.app_es_admin()));
create policy accesos_admin on public.usuarios_aplicaciones for all to anon, authenticated
  using ((select public.app_es_admin())) with check ((select public.app_es_admin()));
grant select, insert, update, delete on public.aplicaciones, public.usuarios_aplicaciones to anon, authenticated;

-- Lista de usuarios (nombres y correos): cada quien ve su propio registro; la lista completa, solo con acceso a IT.
drop policy if exists usuarios_select on public.usuarios;
create policy usuarios_select on public.usuarios for select to anon, authenticated
  using (id = (select public.app_usuario_id()) or (select public.app_tiene_acceso('it')));

-- Datos del área de IT: solo con acceso a la aplicación 'it' (antes bastaba cualquier sesión).
do $$
declare t text;
begin
  foreach t in array array['actividades','historial_actividades','licencias_office','computadoras','mantenimientos','inventario_equipos'] loop
    execute format('drop policy if exists sesion_app on public.%I', t);
    execute format('drop policy if exists acceso_it on public.%I', t);
    execute format('create policy acceso_it on public.%I for all to anon, authenticated using ((select public.app_tiene_acceso(''it''))) with check ((select public.app_tiene_acceso(''it'')))', t);
  end loop;
end $$;
