-- Alterna — 1) código de equipo escrito a mano al crearlo (y fijo después),
--           2) todas las sesiones se cierran a las 12 a.m. (hora de Guatemala),
--           3) "Otras licencias" (reemplaza a Canva, cuya tabla nunca se creó).

/* ───────────── 1) Código de equipo ───────────── */
alter table public.inventario_equipos add column if not exists codigo text;

-- Los equipos que ya existen conservan el código que tenían (EQ-0003…)
update public.inventario_equipos set codigo = 'EQ-' || lpad(id::text, 4, '0') where codigo is null or btrim(codigo) = '';

alter table public.inventario_equipos alter column codigo set not null;
create unique index if not exists inventario_equipos_codigo_unico on public.inventario_equipos (upper(codigo));

create or replace function public.codigo_equipo() returns trigger
 language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.codigo := upper(btrim(coalesce(new.codigo, '')));
    -- Sin código escrito: el de siempre a partir del id
    if new.codigo = '' then new.codigo := 'EQ-' || lpad(new.id::text, 4, '0'); end if;
  elsif new.codigo is distinct from old.codigo then
    raise exception 'El código del equipo no se puede cambiar después de crearlo.' using errcode = 'P0001';
  end if;
  return new;
end $$;

drop trigger if exists trg_codigo_equipo on public.inventario_equipos;
create trigger trg_codigo_equipo before insert or update of codigo on public.inventario_equipos
  for each row execute function public.codigo_equipo();

/* ───────────── 2) Sesiones vencen a las 12 a.m. ───────────── */
-- app_usuario_id() ya exige expira > now(); sesion.js manda al login cuando la sesión deja de valer.
create or replace function public.proxima_medianoche() returns timestamptz
 language sql stable set search_path = public as $$
  select (((now() at time zone 'America/Guatemala')::date + 1)::timestamp) at time zone 'America/Guatemala'
$$;

create or replace function public.sesion_expira_medianoche() returns trigger
 language plpgsql set search_path = public as $$
begin
  new.expira := least(coalesce(new.expira, now() + interval '30 days'), public.proxima_medianoche());
  return new;
end $$;

drop trigger if exists trg_sesion_medianoche on public.sesiones_app;
create trigger trg_sesion_medianoche before insert on public.sesiones_app
  for each row execute function public.sesion_expira_medianoche();

-- Las sesiones abiertas hoy también se cierran esta medianoche
update public.sesiones_app set expira = public.proxima_medianoche() where expira > public.proxima_medianoche();

/* ───────────── 3) Otras licencias ───────────── */
create table if not exists public.licencias_otras (
  id          bigint generated by default as identity primary key,
  software    text not null,
  nombre      text not null,
  correo      text,
  plan        text,
  expiracion  date,
  notas       text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
alter table public.licencias_otras enable row level security;
drop policy if exists acceso_it on public.licencias_otras;
create policy acceso_it on public.licencias_otras for all to anon, authenticated
  using ((select public.app_tiene_acceso('it'))) with check ((select public.app_tiene_acceso('it')));
grant select, insert, update, delete on public.licencias_otras to anon, authenticated;
