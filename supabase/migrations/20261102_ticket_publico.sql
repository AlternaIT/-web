-- Alterna — enlace público de ticket de mantenimiento.
-- Cada ticket tiene un enlace secreto (uuid aleatorio, no adivinable como MANT-2026-0001).
-- Quien tenga el enlace ve SOLO ese ticket, sin iniciar sesión, mediante ver_ticket_publico().
-- Los cambios de estado quedan registrados para mostrar el proceso.

alter table public.mantenimientos
  add column if not exists enlace_publico uuid not null default gen_random_uuid();

create unique index if not exists mantenimientos_enlace_publico_key on public.mantenimientos (enlace_publico);

create table if not exists public.mantenimientos_estados (
  id               bigint generated by default as identity primary key,
  mantenimiento_id bigint not null references public.mantenimientos(id) on delete cascade,
  estado           text not null,
  fecha            timestamptz not null default now()
);

create index if not exists mantenimientos_estados_mant_idx on public.mantenimientos_estados (mantenimiento_id, fecha);

-- Sin políticas: solo se lee a través de ver_ticket_publico() y del trigger.
alter table public.mantenimientos_estados enable row level security;

create or replace function public.registrar_estado_mantenimiento() returns trigger
 language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.estado is distinct from old.estado then
    insert into public.mantenimientos_estados (mantenimiento_id, estado) values (new.id, coalesce(new.estado, 'Programado'));
  end if;
  return new;
end $$;

drop trigger if exists trg_estado_mantenimiento on public.mantenimientos;
create trigger trg_estado_mantenimiento after insert or update of estado on public.mantenimientos
  for each row execute function public.registrar_estado_mantenimiento();

-- Tickets que ya existían: su estado actual como primer paso del historial.
insert into public.mantenimientos_estados (mantenimiento_id, estado, fecha)
select m.id, coalesce(m.estado, 'Programado'), coalesce(m.created_at, now()) from public.mantenimientos m
where not exists (select 1 from public.mantenimientos_estados e where e.mantenimiento_id = m.id);

-- Datos visibles para el usuario: sin correos ni datos internos de otros registros.
create or replace function public.ver_ticket_publico(p_enlace uuid) returns json
 language sql stable security definer set search_path = public as $$
  select json_build_object(
    'numero_ticket',    m.numero_ticket,
    'titulo',           m.titulo,
    'tipo',             m.tipo,
    'prioridad',        m.prioridad,
    'estado',           m.estado,
    'tecnico',          m.tecnico,
    'descripcion',      m.descripcion,
    'fecha_programada', m.fecha_programada,
    'hora_programada',  to_char(m.hora_programada, 'HH24:MI'),
    'fecha_realizada',  m.fecha_realizada,
    'creado',           m.created_at,
    'usuario',          u.nombre,
    'equipo',           nullif(concat_ws(' ', e.tipo, e.marca, e.modelo), ''),
    'numero_serie',     e.numero_serie,
    'historial',        coalesce((select json_agg(json_build_object('estado', h.estado, 'fecha', h.fecha) order by h.fecha)
                                  from public.mantenimientos_estados h where h.mantenimiento_id = m.id), '[]'::json)
  )
  from public.mantenimientos m
  left join public.usuarios u on u.id = m.usuario_id
  left join public.inventario_equipos e on e.id = m.equipo_id
  where m.enlace_publico = p_enlace
$$;

revoke all on function public.ver_ticket_publico(uuid) from public;
grant execute on function public.ver_ticket_publico(uuid) to anon, authenticated;
revoke all on function public.registrar_estado_mantenimiento() from public, anon, authenticated;
