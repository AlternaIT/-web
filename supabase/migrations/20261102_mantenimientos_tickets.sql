-- Alterna — mantenimientos: alinear el esquema con el dashboard.
-- El dashboard trabaja con tickets (numero_ticket, titulo, prioridad, usuario, equipo del inventario)
-- y con la tabla inventario_equipos, que no existían. Solo agrega; no borra nada.
-- computadora_id / computadoras se conservan para la acción "programar_mantenimiento" de la IA.

create table if not exists public.inventario_equipos (
  id                bigint generated by default as identity primary key,
  tipo              text not null,
  marca             text,
  modelo            text,
  numero_serie      text,
  estado            text not null default 'Disponible',
  asignado_a        text,
  usuario_id        bigint references public.usuarios(id) on delete set null,
  procesador        text,
  ram               text,
  almacenamiento    text,
  sistema_operativo text,
  fecha_compra      date,
  notas             text,
  created_at        timestamptz not null default now()
);

alter table public.mantenimientos
  add column if not exists numero_ticket   text,
  add column if not exists titulo          text,
  add column if not exists prioridad       text default 'Media',
  add column if not exists usuario_id      bigint references public.usuarios(id) on delete set null,
  add column if not exists equipo_id       bigint references public.inventario_equipos(id) on delete set null,
  add column if not exists hora_programada time,
  add column if not exists creado_por      text;

alter table public.mantenimientos alter column estado set default 'Programado';

create unique index if not exists mantenimientos_numero_ticket_key on public.mantenimientos (numero_ticket);

-- Misma regla que el resto de tablas: requiere una sesión válida (header x-app-token).
alter table public.inventario_equipos enable row level security;
drop policy if exists sesion_app on public.inventario_equipos;
create policy sesion_app on public.inventario_equipos for all to anon, authenticated
  using ((select public.app_usuario_id()) is not null)
  with check ((select public.app_usuario_id()) is not null);

grant select, insert, update, delete on public.inventario_equipos to anon, authenticated;
